#!/usr/bin/env node
/**
 * build-flags.mjs — generates app/src/data/flags.ts from the flag-icons package.
 *
 * flag-icons is only a devDependency (a generation-time tool). The output is a
 * plain TS module with every flag base64-encoded as a data: URI, so the app
 * has zero runtime dependency on the package and zero network requests to
 * show a flag — required for the offline single-file build (see
 * specs/flag-icons/PLAN.md for why url()-based CSS doesn't survive it).
 *
 * Run:  node scripts/build-flags.mjs
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FLAGS_DIR = resolve(ROOT, 'node_modules/flag-icons/flags/4x3');
const OUT_FILE = resolve(ROOT, 'src/data/flags.ts');

const files = readdirSync(FLAGS_DIR).filter((name) => name.endsWith('.svg')).sort();

const entries = files.map((name) => {
  const code = name.replace(/\.svg$/, '');
  const svg = readFileSync(resolve(FLAGS_DIR, name));
  const dataUri = `data:image/svg+xml;base64,${svg.toString('base64')}`;
  return `  ${code}: ${JSON.stringify(dataUri)},`;
});

const out = `// Generated by scripts/build-flags.mjs from the flag-icons package — do not edit by hand.
// Run \`node scripts/build-flags.mjs\` to regenerate after a flag-icons upgrade.

export const FLAGS: Record<string, string> = {
${entries.join('\n')}
};
`;

writeFileSync(OUT_FILE, out);
console.log(`✓ ${OUT_FILE} (${files.length} flags)`);
